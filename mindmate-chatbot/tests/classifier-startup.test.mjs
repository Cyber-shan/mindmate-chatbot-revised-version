import assert from "node:assert/strict";
import { test } from "node:test";
import { mkdtemp, mkdir, readFile, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { assertPrototypeHealth, classifierFingerprint, findClassifierPython, preparePrototypeClassifier, preparePrototypeModel } from "../scripts/classifier-startup.mjs";

const provenance = {
  model_version: "synthetic-test-v1", model_mode: "prototype", synthetic_data: true,
  language: "en", release_approved: false, prototype_usable: true,
};

async function fixture(t) {
  const directory = await mkdtemp(path.join(tmpdir(), "mindmate-classifier-startup-"));
  t.after(async () => {
    const absolute = path.resolve(directory);
    const relative = path.relative(path.resolve(tmpdir()), absolute);
    assert.ok(relative && !relative.startsWith("..") && !path.isAbsolute(relative) && path.basename(absolute).startsWith("mindmate-classifier-startup-"));
    await rm(absolute, { recursive: true, force: true });
  });
  const root = path.join(directory, "mindmate-chatbot");
  const algorithmRoot = path.join(directory, "mindmate-algorithm");
  await mkdir(root);
  await mkdir(path.join(algorithmRoot, "distress"), { recursive: true });
  const python = path.join(algorithmRoot, ".venv", process.platform === "win32" ? "Scripts/python.exe" : "bin/python");
  await mkdir(path.dirname(python), { recursive: true });
  for (const [relative, contents] of [
    ["prototype.py", "synthetic generator"], ["train.py", "training pipeline"],
    ["requirements.txt", "scikit-learn>=1.8,<2"], ["distress/model.py", "classifier"],
    [path.relative(algorithmRoot, python), "python placeholder"],
  ]) await writeFile(path.join(algorithmRoot, relative), contents);
  const calls = [];
  const run = async (executable, args, options) => {
    calls.push({ executable, args, options });
    if (!args[0].endsWith("prototype.py")) return;
    const output = args[args.indexOf("--output") + 1];
    await mkdir(output, { recursive: true });
    await writeFile(path.join(output, "classifier.joblib"), "trusted test artifact placeholder");
    await writeFile(path.join(output, "evaluation.json"), JSON.stringify(provenance));
  };
  return { root, algorithmRoot, python, calls, run };
}

test("prototype training uses the project environment and reuses only matching artifact inputs", async (t) => {
  const setup = await fixture(t);
  const model = await preparePrototypeModel(setup);
  assert.equal(model.python, setup.python);
  assert.equal(model.modelVersion, provenance.model_version);
  assert.equal(setup.calls.length, 1);
  assert.equal(setup.calls[0].options.inherit, true);
  await preparePrototypeModel(setup);
  assert.equal(setup.calls.length, 1, "unchanged sources should reuse the artifact");
  await writeFile(path.join(setup.algorithmRoot, "distress/model.py"), "updated classifier");
  await preparePrototypeModel(setup);
  assert.equal(setup.calls.length, 2, "changed algorithm sources should retrain");
  await writeFile(path.join(setup.algorithmRoot, "requirements.txt"), "scikit-learn>=1.9,<2");
  await preparePrototypeModel(setup);
  assert.equal(setup.calls.length, 3, "changed dependency requirements should retrain");
});

test("fingerprinting follows installed dependency metadata and excludes generated bytecode", async (t) => {
  const setup = await fixture(t);
  const original = await classifierFingerprint(setup.algorithmRoot);
  await mkdir(path.join(setup.algorithmRoot, "distress", "__pycache__"));
  await writeFile(path.join(setup.algorithmRoot, "distress", "__pycache__", "model.pyc"), "generated");
  assert.equal(await classifierFingerprint(setup.algorithmRoot), original);
  const site = path.join(setup.algorithmRoot, ".venv", process.platform === "win32" ? "Lib/site-packages" : "lib/python3.14/site-packages", "numpy-2.0.dist-info");
  await mkdir(site, { recursive: true });
  await writeFile(path.join(site, "METADATA"), "Version: 2.0");
  const installed = await classifierFingerprint(setup.algorithmRoot);
  assert.notEqual(installed, original);
  await writeFile(path.join(site, "METADATA"), "Version: 2.1");
  assert.notEqual(await classifierFingerprint(setup.algorithmRoot), installed);
});

test("missing environments fail with setup instructions and invalid artifacts never become reusable", async (t) => {
  const setup = await fixture(t);
  await assert.rejects(findClassifierPython(path.join(setup.root, "missing")), /environment is missing/);
  const invalidRun = async (executable, args, options) => {
    await setup.run(executable, args, options);
    const output = args[args.indexOf("--output") + 1];
    await writeFile(path.join(output, "evaluation.json"), JSON.stringify({ ...provenance, release_approved: true }));
  };
  await assert.rejects(preparePrototypeModel({ ...setup, run: invalidRun }), /did not produce a valid English synthetic/);
  await assert.rejects(readFile(path.join(setup.algorithmRoot, "artifacts", "prototype", ".startup.json")), { code: "ENOENT" });
});

test("matching running classifiers are reused with explicit prototype configuration", async (t) => {
  const setup = await fixture(t);
  const env = {};
  await preparePrototypeClassifier({ ...setup, env, fetchHealth: async () => ({ ready: true, ...provenance }) });
  assert.equal(env.DISTRESS_CLASSIFIER_MODE, "prototype");
  assert.equal(env.DISTRESS_CLASSIFIER_URL, "http://127.0.0.1:8001");
  assert.equal(setup.calls.length, 1, "training only; do not start an already healthy classifier");
});

test("an absent classifier starts under the existing launcher lifecycle and waits for exact readiness", async (t) => {
  const setup = await fixture(t);
  const env = { DISTRESS_CLASSIFIER_URL: "http://127.0.0.1:8123" };
  let healthReads = 0;
  let waited = false;
  const model = await preparePrototypeClassifier({
    ...setup, env,
    fetchHealth: async () => ++healthReads === 1 ? null : { ready: true, ...provenance },
    wait: async (ready, options) => { waited = true; assert.equal(options.description, "Prototype classifier"); assert.equal(await ready(), true); },
  });
  assert.equal(waited, true);
  const server = setup.calls[1];
  assert.deepEqual(server.args, [path.join(model.algorithmRoot, "serve.py"), "--model", model.artifact, "--host", "127.0.0.1", "--port", "8123"]);
  assert.equal(server.options.background, true);
  assert.equal(server.options.env, env);
  assert.equal(server.options.serviceName, "prototype classifier");
});

test("occupied or incompatible classifiers are rejected rather than overwritten", async (t) => {
  const setup = await fixture(t);
  for (const health of [
    {}, { ready: false, ...provenance }, { ready: true, ...provenance, synthetic_data: false },
    { ready: true, ...provenance, model_version: "stale-version" },
    { ready: true, ...provenance, language: "other" }, { ready: true, ...provenance, prototype_usable: false },
  ]) assert.throws(() => assertPrototypeHealth(health, provenance.model_version), /incompatible or stale service/);
  await assert.rejects(preparePrototypeClassifier({ ...setup, env: {}, fetchHealth: async () => ({ ready: true, ...provenance, release_approved: true }) }), /incompatible or stale service/);
  assert.equal(setup.calls.length, 1, "never launch another service over an occupied port");
});

test("the prototype launcher rejects remote and non-origin addresses before training", async (t) => {
  const setup = await fixture(t);
  for (const url of ["http://example.com:8001", "https://127.0.0.1:8001", "http://user:secret@localhost:8001", "http://localhost:8001/predict", "http://localhost:8001?token=secret"]) {
    await assert.rejects(preparePrototypeClassifier({ ...setup, env: { DISTRESS_CLASSIFIER_URL: url } }));
  }
  assert.equal(setup.calls.length, 0);
});
